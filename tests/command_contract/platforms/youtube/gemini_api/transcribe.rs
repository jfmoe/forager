use std::fs;
use std::path::{Path, PathBuf};

use serde_json::json;

use crate::support::gemini_api::{self, MODEL, MODEL_VERSION};
use crate::support::youtube_api_samples::{videos_page, zoo_video};
use crate::support::{Fixture, RunEnvironment, ok_json, payload, request_json, stderr};
use crate::support::{path, query};

const CHAPTERED: &str = "The first video.\n\n0:00 Intro\n0:05 The cool thing\n0:14 End";

fn transcribe(environment: &RunEnvironment, arguments: &[&str]) -> std::process::Output {
    let mut command = vec!["platform", "youtube", "transcribe"];
    command.extend_from_slice(arguments);
    environment.run(&command)
}

#[test]
fn a_model_transcript_is_written_beside_the_metadata_with_its_model_and_usage() {
    let api = Fixture::start_sequence(vec![ok_json(&videos_page(&[zoo_video(CHAPTERED)]))]);
    let gemini = Fixture::start_sequence(vec![gemini_api::transcription()]);
    let environment = RunEnvironment::new(&gemini_api::config(&api.url, &gemini.url));
    let content_dir = tempfile::tempdir().expect("content directory");
    let content_path = content_dir
        .path()
        .join("youtube-jNQXAC9IVRw-transcribed.md");

    let output = transcribe(
        &environment,
        &[
            "youtube:jNQXAC9IVRw",
            "--content-dir",
            content_dir.path().to_str().expect("UTF-8 path"),
        ],
    );
    let metadata_request = api.finish();
    let model_request = gemini.finish();
    let body = request_json(&model_request);
    let document = fs::read_to_string(&content_path).unwrap_or_default();

    assert_eq!(
        (
            output.status.code(),
            path(&metadata_request),
            query(&metadata_request).get("part").cloned(),
            path(&model_request),
            &body["contents"][0]["parts"][0],
            &body["generationConfig"]["responseMimeType"],
            &body["generationConfig"]["responseSchema"]["required"],
            &body["generationConfig"]["responseSchema"]["properties"]["segments"]["items"]["required"],
        ),
        (
            Some(0),
            "/youtube/v3/videos".to_owned(),
            Some("snippet,contentDetails,statistics,status,liveStreamingDetails".to_owned()),
            format!("/v1beta/models/{MODEL}:generateContent"),
            &json!({"fileData": {"mimeType": "video/*", "fileUri": "https://www.youtube.com/watch?v=jNQXAC9IVRw"}}),
            &json!("application/json"),
            &json!(["language", "segments"]),
            &json!(["start", "end", "text"]),
        ),
        "stderr: {}",
        stderr(&output)
    );
    assert_eq!(
        payload(&output),
        json!({
            "platform": "youtube",
            "provider": "gemini_api",
            "ref": "youtube:jNQXAC9IVRw",
            "url": "https://www.youtube.com/watch?v=jNQXAC9IVRw",
            "depth": "full_text",
            "title": "Me at the zoo",
            "authors": ["Example Zoo Visitor"],
            "published": "2005-04-24T03:31:52Z",
            "channel_ref": "youtube:channel/UCExampleZooVisitor00001",
            "snippet": null,
            "duration_seconds": 19,
            "live_status": "none",
            "views": 444_694_156,
            "likes": 20_083_234,
            "comments": 10_641_589,
            "language": "en",
            "has_captions": true,
            "caption_tracks": null,
            "transcript": {"language": "en", "source": "model", "cues": 3, "paragraphs": 3},
            "content_url": "https://www.youtube.com/watch?v=jNQXAC9IVRw",
            "content_provider": "gemini_api",
            "content_path": content_path.display().to_string(),
            "content_len": document.chars().count(),
            "model": MODEL_VERSION,
            "usage": gemini_api::usage()
        })
    );
    assert!(
        document.contains(
            "- Transcript: `en`, generated by a model that watched and listened to the video\n\n> A model generated this transcript; it is not guaranteed to be verbatim."
        ) && document.contains(
            "### The cool thing\n\n[00:05](https://www.youtube.com/watch?v=jNQXAC9IVRw&t=5s) The cool thing"
        ) && !document.contains("past the end"),
        "{document}"
    );
    assert!(
        stderr(&output).contains("dropped 1 model transcript segment(s)"),
        "stderr: {}",
        stderr(&output)
    );
}

/// Runs a transcription whose system temporary directory is `temp`.
fn transcribe_with_temp(
    environment: &RunEnvironment,
    arguments: &[&str],
    temp: &Path,
) -> std::process::Output {
    let mut command = vec!["platform", "youtube", "transcribe"];
    command.extend_from_slice(arguments);
    let temp = temp.to_str().expect("UTF-8 path");
    environment.run_with_env(&command, &[("TMPDIR", temp), ("TMP", temp), ("TEMP", temp)])
}

fn files_under(directory: &Path) -> Vec<PathBuf> {
    let mut files = Vec::new();
    for entry in fs::read_dir(directory).expect("read directory") {
        let path = entry.expect("directory entry").path();
        if path.is_dir() {
            files.extend(files_under(&path));
        } else {
            files.push(path);
        }
    }
    files
}

#[test]
fn without_a_content_directory_the_transcript_is_written_under_the_system_temporary_directory() {
    let api = Fixture::start_sequence(vec![ok_json(&videos_page(&[zoo_video(CHAPTERED)]))]);
    let gemini = Fixture::start_sequence(vec![gemini_api::transcription()]);
    let environment = RunEnvironment::new(&gemini_api::config(&api.url, &gemini.url));
    let temp = tempfile::tempdir().expect("temporary directory");

    let output = transcribe_with_temp(&environment, &["youtube:jNQXAC9IVRw"], temp.path());
    api.finish();
    gemini.finish();
    let path = payload(&output)["content_path"]
        .as_str()
        .map(PathBuf::from)
        .expect("content path");

    assert_eq!(
        (
            output.status.code(),
            path.starts_with(temp.path().join("forager-platform")),
            path.ends_with("youtube-jNQXAC9IVRw-transcribed.md"),
            files_under(temp.path()),
        ),
        (Some(0), true, true, vec![path.clone()]),
        "stderr: {}",
        stderr(&output)
    );
}

#[test]
fn the_content_format_prints_the_transcript_and_writes_no_file() {
    let api = Fixture::start_sequence(vec![ok_json(&videos_page(&[zoo_video(CHAPTERED)]))]);
    let gemini = Fixture::start_sequence(vec![gemini_api::transcription()]);
    let environment = RunEnvironment::new(&gemini_api::config(&api.url, &gemini.url));
    let temp = tempfile::tempdir().expect("temporary directory");

    let output = transcribe_with_temp(
        &environment,
        &["youtube:jNQXAC9IVRw", "--format", "content"],
        temp.path(),
    );
    api.finish();
    gemini.finish();

    assert_eq!(
        (
            output.status.code(),
            String::from_utf8_lossy(&output.stdout).starts_with("# Me at the zoo\n"),
            files_under(temp.path()),
        ),
        (Some(0), true, Vec::<PathBuf>::new()),
        "stderr: {}",
        stderr(&output)
    );
}
