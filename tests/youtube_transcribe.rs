mod support;

use std::fs;

use serde_json::json;

use support::gemini_api::{self, MODEL, MODEL_VERSION};
use support::youtube::{path, payload, query, stderr, videos_page, zoo_video};
use support::{Fixture, RunEnvironment, request_json};

const CHAPTERED: &str = "The first video.\n\n0:00 Intro\n0:05 The cool thing\n0:14 End";

fn transcribe(environment: &RunEnvironment, arguments: &[&str]) -> std::process::Output {
    let mut command = vec!["platform", "youtube", "transcribe"];
    command.extend_from_slice(arguments);
    environment.run(&command)
}

/// The JSON transcript a model writes as its answer text.
fn transcript(segments: &serde_json::Value) -> String {
    json!({"language": "en", "segments": segments}).to_string()
}

#[test]
fn a_model_transcript_is_written_beside_the_metadata_with_its_model_and_usage() {
    let api = Fixture::start_sequence(vec![videos_page(&[zoo_video(CHAPTERED)])]);
    let gemini = Fixture::start_sequence(vec![gemini_api::answer(&transcript(&json!([
        {"start": 1.2, "end": 3.4, "text": "All right, so here we are, in front of the elephants."},
        {"start": 5.3, "end": 12.6, "text": "The cool thing about these guys is that they have really long trunks."},
        {"start": 16.9, "end": 18.9, "text": "And that's pretty much all there is to say."},
        {"start": 40.0, "end": 41.0, "text": "A segment past the end."}
    ])))]);
    let environment = RunEnvironment::new(&gemini_api::config(&api.url, &gemini.url));
    let content_dir = tempfile::tempdir().expect("content directory");
    let content_path = content_dir
        .path()
        .join("youtube-jNQXAC9IVRw-transcribed.md");

    let output = transcribe(
        &environment,
        &[
            "youtube:jNQXAC9IVRw",
            "--content-dir",
            content_dir.path().to_str().expect("UTF-8 path"),
        ],
    );
    let metadata_request = api.finish();
    let model_request = gemini.finish();
    let body = request_json(&model_request);
    let document = fs::read_to_string(&content_path).unwrap_or_default();

    assert_eq!(
        (
            output.status.code(),
            path(&metadata_request),
            query(&metadata_request).get("part").cloned(),
            path(&model_request),
            &body["contents"][0]["parts"][0],
            &body["generationConfig"]["responseMimeType"],
            &body["generationConfig"]["responseSchema"]["required"],
            &body["generationConfig"]["responseSchema"]["properties"]["segments"]["items"]["required"],
        ),
        (
            Some(0),
            "/youtube/v3/videos".to_owned(),
            Some("snippet,contentDetails,statistics,status,liveStreamingDetails".to_owned()),
            format!("/v1beta/models/{MODEL}:generateContent"),
            &json!({"fileData": {"mimeType": "video/*", "fileUri": "https://www.youtube.com/watch?v=jNQXAC9IVRw"}}),
            &json!("application/json"),
            &json!(["language", "segments"]),
            &json!(["start", "end", "text"]),
        ),
        "stderr: {}",
        stderr(&output)
    );
    assert_eq!(
        payload(&output),
        json!({
            "platform": "youtube",
            "provider": "gemini_api",
            "ref": "youtube:jNQXAC9IVRw",
            "url": "https://www.youtube.com/watch?v=jNQXAC9IVRw",
            "depth": "full_text",
            "title": "Me at the zoo",
            "authors": ["jawed"],
            "published": "2005-04-24T03:31:52Z",
            "channel_ref": "youtube:channel/UC4QobU6STFB0P71PMvOGN5A",
            "snippet": null,
            "duration_seconds": 19,
            "live_status": "none",
            "views": 444_694_156,
            "likes": 20_083_234,
            "comments": 10_641_589,
            "language": "en",
            "has_captions": true,
            "caption_tracks": null,
            "transcript": {"language": "en", "source": "model", "cues": 3, "paragraphs": 3},
            "content_url": "https://www.youtube.com/watch?v=jNQXAC9IVRw",
            "content_provider": "gemini_api",
            "content_path": content_path.display().to_string(),
            "content_len": document.chars().count(),
            "model": MODEL_VERSION,
            "usage": gemini_api::usage()
        })
    );
    assert!(
        document.contains(
            "- Transcript: `en`, generated by a model that watched and listened to the video\n\n> A model generated this transcript; it is not guaranteed to be verbatim."
        ) && document.contains(
            "### The cool thing\n\n[00:05](https://www.youtube.com/watch?v=jNQXAC9IVRw&t=5s) The cool thing"
        ) && !document.contains("past the end"),
        "{document}"
    );
    assert!(
        stderr(&output).contains("dropped 1 model transcript segment(s)"),
        "stderr: {}",
        stderr(&output)
    );
}

#[test]
fn a_video_without_a_description_is_transcribed_and_content_prints_the_document() {
    let api = Fixture::start_sequence(vec![videos_page(&[zoo_video("")])]);
    let gemini = Fixture::start_sequence(vec![gemini_api::answer(&transcript(&json!([
        {"start": 1.2, "end": 3.4, "text": "All right, so here we are."}
    ])))]);
    let environment = RunEnvironment::new(&gemini_api::config(&api.url, &gemini.url));

    let output = transcribe(
        &environment,
        &["youtube:jNQXAC9IVRw", "--format", "content"],
    );
    api.finish();
    gemini.finish();
    let document = String::from_utf8_lossy(&output.stdout);

    assert_eq!(output.status.code(), Some(0), "stderr: {}", stderr(&output));
    assert!(
        document.starts_with("# Me at the zoo\n")
            && document.contains("## Description\n\n(none)\n")
            && document.contains("[00:01](https://www.youtube.com/watch?v=jNQXAC9IVRw&t=1s) All right, so here we are."),
        "{document}"
    );
}

#[test]
fn a_truncated_or_invalid_model_transcript_is_quality_and_writes_no_file() {
    let outcomes = [
        gemini_api::generate(
            r#"{"language": "en", "segments": [{"start": 1.2, "end": 3.4, "text": "All ri"#,
            "MAX_TOKENS",
        ),
        gemini_api::answer("Here is the transcript: all right, so here we are."),
    ]
    .map(|response| {
        let api = Fixture::start_sequence(vec![videos_page(&[zoo_video(CHAPTERED)])]);
        let gemini = Fixture::start_sequence(vec![response]);
        let environment = RunEnvironment::new(&gemini_api::config(&api.url, &gemini.url));
        let content_dir = tempfile::tempdir().expect("content directory");

        let output = transcribe(
            &environment,
            &[
                "youtube:jNQXAC9IVRw",
                "--content-dir",
                content_dir.path().to_str().expect("UTF-8 path"),
            ],
        );
        api.finish();
        gemini.finish();
        let written = fs::read_dir(content_dir.path())
            .map(Iterator::count)
            .unwrap_or_default();
        (
            output.status.code(),
            payload(&output)["error_kind"].clone(),
            written,
        )
    });

    assert_eq!(
        outcomes,
        [
            (Some(5), json!("quality"), 0),
            (Some(5), json!("quality"), 0)
        ]
    );
}

#[test]
fn a_video_the_metadata_check_cannot_read_is_not_sent_to_the_model() {
    let api = Fixture::start_sequence(vec![videos_page(&[])]);
    let gemini = Fixture::start_canary();
    let environment = RunEnvironment::new(&gemini_api::config(&api.url, &gemini.url));

    let output = transcribe(&environment, &["youtube:aaaaaaaaaaa"]);
    api.finish();

    assert_eq!(
        (
            output.status.code(),
            payload(&output)["error_kind"].clone(),
            gemini.finish_all().len()
        ),
        (Some(4), json!("parameter"), 0),
        "stderr: {}",
        stderr(&output)
    );
}
